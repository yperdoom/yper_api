import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import { MongoMemoryServer } from 'mongodb-memory-server';
import { buildApp } from '../src/app.js';
import { projectFinance, occurrence } from '../src/services/financeProjection.js';
import { FinanceAccount, FinanceEntry, FinanceEstimate } from '../src/models/yper/Finance.js';

const account = { _id: 'a', name: 'Principal', kind: 'operational', openingDate: '2026-10-01', openingBalanceCents: 100000 };
const reserve = { _id: 'b', name: 'Reserva', kind: 'reserve', openingDate: '2026-10-01', openingBalanceCents: 50000 };
const base = { _id: 'expense', revision: 0, description: 'Compra', type: 'expense', account: 'a', category: 'Casa', group: 'card', creditor: 'Cartão', amountCents: 10000, date: '2026-10-31', repeat: 'installments', installment: 2, totalInstallments: 4, overrides: [] };
const input = { accounts: [account, reserve], entries: [base], estimates: [], from: '2026-10', count: 6, today: '2026-10-08' };
let result = projectFinance(input);
assert.deepEqual(result.months.map(m => m.expenseCents), [10000,10000,10000,0,0,0]);
assert.equal(occurrence(base, '2026-11').dueDate, '2026-11-30');
assert.equal(occurrence({ ...base, repeat: 'monthly' }, '2027-02').dueDate, '2027-02-28');
assert.equal(result.months[2].balanceCents, 120000);
assert.equal(result.accounts[0].currentBalanceCents, 100000);
assert.equal(projectFinance({ ...input, from: '2025-01', count: 3, entries: [{ ...base, repeat: 'once', overrides: [{ month: '2026-10', status: 'paid', paidDate: '2026-10-07' }] }] }).accounts[0].currentBalanceCents, 90000);
const transfer = { ...base, _id: 'transfer', type: 'transfer', repeat: 'once', date: '2026-10-08', toAccount: 'b', amountCents: 20000 };
result = projectFinance({ ...input, entries: [transfer] });
assert.equal(result.months[0].expenseCents, 0);
assert.equal(result.months[0].balanceCents, 150000);
assert.equal(result.months[0].operationalCents, 80000);
assert.equal(result.months[0].reserveCents, 70000);
assert.equal(projectFinance({ ...input, entries: [transfer], accountId: 'a' }).months[0].resultCents, -20000);
assert.equal(projectFinance({ ...input, entries: [transfer], accountId: 'b' }).months[0].resultCents, 20000);
result = projectFinance({ ...input, estimates: [{ _id: 'est', month: '2026-10', account: 'a', category: 'Casa', amountCents: 15000 }] });
assert.equal(result.months[0].expenseCents, 15000);
assert.equal(result.months[0].estimateCents, 5000);
result = projectFinance({ ...input, entries: [{ ...base, overrides: [{ month: '2026-11', status: 'paid', paidDate: '2026-10-07' }] }] });
assert.equal(result.accounts[0].currentBalanceCents, 90000);
assert.equal(result.months[0].expenseCents, 20000);
assert.equal(result.months[1].expenseCents, 0);
result = projectFinance({ ...input, entries: [{ ...base, repeat: 'monthly', endDate: '2026-11-30' }] });
assert.deepEqual(result.months.map(m => m.expenseCents), [10000,10000,0,0,0,0]);
result = projectFinance({ ...input, entries: [{ ...base, repeat: 'once', date: '2026-09-15' }] });
assert.equal(result.months[0].overdueCents, 10000);
assert.equal(result.accounts[0].currentBalanceCents, 100000);
assert.equal(projectFinance({ ...input, accounts: [{ ...account, openingBalanceCents: null }] }).months[0].balanceCents, null);
assert.equal(projectFinance({ ...input, entries: [{ ...base, overrides: [{ month: '2026-10', status: 'cancelled' }] }] }).months[0].expenseCents, 0);

process.env.JWT_SECRET = 'finance-test-only';
const mongo = await MongoMemoryServer.create();
const app = buildApp();
try {
  await mongoose.connect(mongo.getUri(), { dbName: 'finance-test' });
  await Promise.all([FinanceAccount.init(), FinanceEntry.init(), FinanceEstimate.init()]);
  const setup = (await app.inject({ method: 'POST', url: '/auth/setup', payload: { email: 'finance@test.com', password: 'secret123' } })).json();
  const headers = { authorization: `Bearer ${setup.token}` };
  const call = (method, path, payload, h = headers) => app.inject({ method, url: `/yper/finance${path}`, payload, headers: h });
  assert.equal((await call('GET', '/accounts', undefined, {})).statusCode, 401);
  let response = await call('POST', '/accounts', { name: 'Principal', kind: 'operational', openingDate: '2026-10-01', openingBalanceCents: 100000 });
  assert.equal(response.statusCode, 200, response.body);
  const a = response.json().account;
  const b = (await call('POST', '/accounts', { name: 'Reserva', kind: 'reserve', openingDate: '2026-10-01', openingBalanceCents: null })).json().account;
  assert.equal((await call('POST', '/accounts', { ...a, openingBalanceCents: '100' })).statusCode, 400);
  const payload = { ...base, account: a._id, _id: undefined, user: new mongoose.Types.ObjectId().toString() };
  const e = (await call('POST', '/entries', payload)).json().entry;
  assert.equal(e.user, setup.user.id);
  assert.equal((await call('POST', '/entries', { ...payload, amountCents: 1.01 })).statusCode, 400);
  assert.equal((await call('POST', '/entries', { ...payload, date: '2026-02-30' })).statusCode, 400);
  assert.equal((await call('POST', '/entries', { ...payload, installment: 5, totalInstallments: 4 })).statusCode, 400);
  assert.equal((await call('POST', '/entries', { ...payload, type: 'transfer', toAccount: a._id })).statusCode, 400);
  const occurrencePath = `/entries/${e._id}/occurrences/2026-10`;
  assert.equal((await call('PUT', occurrencePath, { revision: 0, status: 'paid', paidDate: '2026-10-08' })).statusCode, 200);
  assert.equal((await call('PUT', occurrencePath, { revision: 0, status: 'cancelled' })).statusCode, 409);
  assert.equal((await call('PUT', `/entries/${e._id}`, { ...payload, revision: 1 })).statusCode, 409);
  assert.equal((await call('DELETE', `/entries/${e._id}?revision=1`)).statusCode, 409);
  assert.equal((await call('DELETE', `/accounts/${a._id}?revision=0`)).statusCode, 409);
  const projected = (await call('GET', `/projection?from=2026-10&count=6&today=2026-10-08&account=${a._id}`)).json();
  assert.equal(projected.months[0].paidExpenseCents, 10000);
  assert.equal(projected.accounts[0].currentBalanceCents, 90000);
  assert.equal(await FinanceEntry.countDocuments(), 1, 'projection must not materialize new entries');
  assert.equal((await call('GET', '/projection?from=bad&count=999')).statusCode, 400);
  await app.inject({ method: 'POST', url: '/auth/users', headers, payload: { email: 'other@test.com', password: 'secret123', apps: ['yper'] } });
  const other = (await app.inject({ method: 'POST', url: '/auth/login', payload: { email: 'other@test.com', password: 'secret123' } })).json();
  const outsider = { authorization: `Bearer ${other.token}` };
  assert.deepEqual((await call('GET', '/accounts', undefined, outsider)).json().accounts, []);
  assert.equal((await call('POST', '/entries', payload, outsider)).statusCode, 404);
  assert.equal((await call('PUT', occurrencePath, { revision: 1, status: 'cancelled' }, outsider)).statusCode, 404);
  assert.equal((await call('GET', `/projection?from=2026-10&account=${a._id}`, undefined, outsider)).statusCode, 404);
  assert.equal((await call('POST', '/estimates', { month: '2026-10', account: a._id, category: 'Casa', amountCents: 15000 })).statusCode, 200);
  assert.equal((await call('POST', '/estimates', { month: '2026-10', account: a._id, category: 'Casa', amountCents: 15000 })).statusCode, 409);
  assert.equal((await call('DELETE', `/accounts/${b._id}?revision=0`)).statusCode, 200);
  console.log('FINANCE OK: projections, installments, month ends, transfers, reserves, estimates, settlement, ownership, validation and revision conflicts');
} finally { await app.close(); await mongoose.disconnect(); await mongo.stop(); }
